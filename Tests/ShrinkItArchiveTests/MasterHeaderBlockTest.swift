import XCTest
@testable import ShrinkItArchive

/**
 * Exercise the Master Header Block.
 * For right now, we just grab a "real" header
 * and check it against our computed values.
 * @author robgreene@users.sourceforge.net
 */
public class MasterHeaderBlockTest : XCTestCase {
	public func testWithValidCrc() throws {
		let bs = LittleEndianByteInputStream([
				0x4e, UInt8(0xf5), 0x46, UInt8(0xe9), 0x6c, UInt8(0xe5), UInt8(0xdc), 0x1b,
				0x2d, 0x00, 0x00, 0x00, 0x38, 0x0c, 0x14, 0x5f,
				0x08, 0x07, 0x30, 0x04, 0x29, 0x0d, 0x14, 0x5f,
				0x08, 0x07, 0x01, 0x04, 0x01, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, UInt8(0xae), UInt8(0xac),
				0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
			])
    let b = try MasterHeaderBlock(bs);
		// Using byte values since it should be a bit more clear where they came from
		XCTAssertEqual(0x1bdc, b.getMasterCrc());
    XCTAssertEqual(0x2d, b.getTotalRecords());
    try TestHelper.checkDate([0x38, 0x0c, 0x14, 0x5f, 0x08, 0x07, 0x30, 0x04], b.getArchiveCreateWhen()!);
    try TestHelper.checkDate([0x29, 0x0d, 0x14, 0x5f, 0x08, 0x07, 0x01, 0x04], b.getArchiveModWhen()!);
    XCTAssertEqual(0x01, b.getMasterVersion());
    XCTAssertEqual(0x1acae, b.getMasterEof());
    XCTAssertTrue(b.isValidCrc());
	}

	public func testWithInvalidCrc() throws  {
		let bs = LittleEndianByteInputStream([
				0x4e, UInt8(0xf5), 0x46, UInt8(0xe9), 0x6c, UInt8(0xe5), 0x00, 0x00,	// <-- Bad CRC!
				0x2d, 0x00, 0x00, 0x00, 0x38, 0x0c, 0x14, 0x5f,
				0x08, 0x07, 0x30, 0x04, 0x29, 0x0d, 0x14, 0x5f,
				0x08, 0x07, 0x01, 0x04, 0x01, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, UInt8(0xae), UInt8(0xac),
				0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
			])
    let b = try MasterHeaderBlock(bs)
    XCTAssertFalse(b.isValidCrc())
	}
}
